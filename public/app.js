function counter(length, limit) {
  const ratio = length / limit;
  const tone = length > limit ? 'over' : ratio > 0.92 ? 'tight' : '';
  return `<span class="counter ${tone}">${length} / ${limit} characters ${length <= limit ? '&check;' : '&times;'}</span>`;
}

