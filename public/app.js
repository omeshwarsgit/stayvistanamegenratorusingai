/**
 * app.js — dashboard behaviour.
 *
 * All listing content is rendered through esc(), because everything shown here
 * came off a third-party page.
 */

const $ = (id) => document.getElementById(id);

const state = {
  lastUrl: '',
  pastedText: '',
  removed: new Set(),
  confirmed: new Set(),
  snippet: null,
  capturePoll: null,
  result: null,
  busy: false,
};

const OTA_PATTERNS = [
  [/(^|\.)stayvista\.com$/i, 'StayVista'],
  [/(^|\.)vistarooms\.com$/i, 'StayVista'],
  [/(^|\.)airbnb\.[a-z.]+$/i, 'Airbnb'],
  [/(^|\.)abnb\.me$/i, 'Airbnb'],
  [/(^|\.)booking\.com$/i, 'Booking.com'],
  [/(^|\.)makemytrip\.(com|ae)$/i, 'MakeMyTrip'],
  [/(^|\.)agoda\.(com|net)$/i, 'Agoda'],
  [/(^|\.)goibibo\.com$/i, 'Goibibo'],
];

const SOURCE_LABEL = {
  'json-ld': ['Structured data', 'strong'],
  embedded: ['Page data', 'strong'],
  meta: ['Page metadata', 'strong'],
  'page-text': ['Read from page', 'weak'],
  api: ['API response', 'strong'],
  capture: ['Captured in your browser', 'strong'],
  url: ['From the URL', 'weak'],
  'listing-title': ['Listing title', 'strong'],
  'amenity-list': ['Amenity list', 'strong'],
  manual: ['From your details', 'manual'],
  'manual-added': ['Added by you', 'manual'],
  stayvista: ['StayVista page', 'strong'],
};

/* ------------------------------------------------------------------- setup */

init();

function init() {
  $('searchForm').addEventListener('submit', (e) => {
    e.preventDefault();
    runAnalysis({ fresh: true });
  });
  $('url').addEventListener('input', updateOtaChip);
  $('regenerateBtn').addEventListener('click', () => runAnalysis({ fresh: false }));
  $('resetFixBtn').addEventListener('click', resetCorrections);
  $('maxChars').addEventListener('change', () => {
    $('fixMaxChars').value = $('maxChars').value;
  });
  $('fixMaxChars').addEventListener('change', () => {
    $('maxChars').value = $('fixMaxChars').value;
  });
  document.addEventListener('click', onCopyClick);
  loadStatus();
}

async function loadStatus() {
  try {
    const res = await fetch('/api/status');
    const status = await res.json();
    const badge = $('modeBadge');
    const dot = badge.querySelector('.dot');
    if (status.enabled) {
      $('modeText').textContent = `Engine + Claude (${status.model})`;
      dot.classList.remove('engine');
      badge.title = 'Names are generated by the rules engine and by Claude, then both are validated against the listing.';
      $('aiToggleWrap').hidden = false;
    } else {
      $('modeText').textContent = 'Engine mode';
      badge.title = 'No ANTHROPIC_API_KEY is set, so names come from the built-in naming engine. Set a key in .env to add the Claude pass.';
    }
  } catch {
    $('modeText').textContent = 'Engine mode';
  }
}

function updateOtaChip() {
  const chip = $('otaChip');
  const raw = $('url').value.trim();
  if (!raw) {
    chip.hidden = true;
    return;
  }
  let host = '';
  try {
    host = new URL(/^https?:\/\//i.test(raw) ? raw : `https://${raw}`).hostname;
  } catch {
    chip.hidden = true;
    return;
  }
  const hit = OTA_PATTERNS.find(([re]) => re.test(host));
  chip.hidden = false;
  chip.textContent = hit ? hit[1] : 'Unrecognised OTA';
  chip.classList.toggle('known', Boolean(hit));
}

/* ---------------------------------------------------------------- analysis */

async function runAnalysis({ fresh }) {
  if (state.busy) return;
  const url = $('url').value.trim();
  if (fresh) {
    if (!url) {
      showError({ error: 'Enter a property listing URL to analyse.', hint: 'Paste the full URL of one property page.' });
      return;
    }
    state.removed = new Set();
    state.confirmed = new Set();
    state.pastedText = '';
    clearCorrections();
  }
  state.lastUrl = url || state.lastUrl;

  const body = {
    url: state.lastUrl,
    maxChars: Number($(fresh ? 'maxChars' : 'fixMaxChars').value) || 50,
    useAi: $('useAi') ? $('useAi').checked : true,
    pastedText: state.pastedText || undefined,
    overrides: fresh ? {} : collectOverrides(),
  };

  stopCapturePolling();
  setBusy(true);
  try {
    const res = await fetch('/api/analyze', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(body),
    });
    const data = await res.json();
    if (!data.ok) {
      showError(data);
      return;
    }
    state.result = data;
    render(data);
  } catch (err) {
    showError({ error: 'Could not reach the local server.', detail: String(err && err.message) });
  } finally {
    setBusy(false);
  }
}

