function renderCorrectionPanel(data) {
  const a = data.analysis;
  const setIf = (id, value) => {
    const el = $(id);
    const incoming = value == null ? '' : String(value);
    const untouched = !el.value || el.value === (el.dataset.prefill || '');
    if (untouched) {
      el.value = incoming;
      el.dataset.prefill = incoming;
    }
  };
  setIf('fixName', a.name && a.name.value);
  setIf('fixLocation', a.location && a.location.value);
  setIf('fixType', a.propertyType && a.propertyType.value);
  setIf('fixBedrooms', a.bedrooms && a.bedrooms.value);
  setIf('fixGuests', a.guests && a.guests.value);
  setIf('fixBathrooms', a.bathrooms && a.bathrooms.value);
  $('fixMaxChars').value = data.limit;
  $('maxChars').value = data.limit;

  const chipSource = data.usps.ranked.filter((u) => u.titleWorthy);
  const known = new Set(chipSource.map((u) => u.id));
  const chips = [
    ...chipSource.map((u) => ({ id: u.id, label: u.label, removed: false })),
    ...[...state.removed].filter((id) => !known.has(id)).map((id) => ({
      id,
      label: (a.removedUsps || []).find(() => false) || prettyId(id),
      removed: true,
    })),
  ];

  $('removeChips').innerHTML = chips.length
    ? chips.map((c) => `
      <button type="button" class="chip${c.removed || state.removed.has(c.id) ? ' removed' : ''}" data-usp="${esc(c.id)}">
        ${esc(c.label)} <span class="x">${c.removed || state.removed.has(c.id) ? '+' : '&times;'}</span>
      </button>`).join('')
    : '<span class="hint">No USPs to remove.</span>';

  for (const chip of $('removeChips').querySelectorAll('.chip')) {
    chip.addEventListener('click', () => {
      const id = chip.dataset.usp;
      if (state.removed.has(id)) state.removed.delete(id);
      else state.removed.add(id);
      chip.classList.toggle('removed');
      chip.querySelector('.x').innerHTML = state.removed.has(id) ? '+' : '&times;';
    });
  }
}

function renderFoot(data) {
  const bits = [];
  if (data.manualUsed) bits.push('Source: details you provided');
  else bits.push(data.fetch.ok ? `Source: live listing page (HTTP ${data.fetch.status})` : 'Source: the listing page');
  const route = describeRoute(data.extraction);
  if (route) bits.push(`Read via: ${esc(route)}`);
  if (data.finalUrl) bits.push(`<a href="${esc(data.finalUrl)}" target="_blank" rel="noreferrer noopener">Open the listing</a>`);
  bits.push(data.ai && data.ai.used ? `Claude pass ran on ${esc(data.ai.model || '')}` : 'Engine only');
  bits.push('Names use verified listing facts and your corrections only.');
  $('foot').innerHTML = bits.join(' &nbsp;·&nbsp; ');
}

/** Which strategy actually produced the data, for the footer and error state. */
function describeRoute(extraction) {
  if (!extraction || !extraction.steps) return null;
  const wins = extraction.steps.filter((s) => s.status === 'success' && s.strategy !== 'fetch');
  if (!wins.length) return null;
  return wins.map((s) => s.label.toLowerCase()).join(' + ');
}

function strategyList(steps) {
  if (!steps || !steps.length) return '';
  const rows = steps.map((s) => {
    const mark = s.status === 'success' ? '&check;' : s.status === 'skipped' ? '&ndash;' : '&times;';
    const fields = s.fields ? ` (${s.fields} fields)` : '';
    return `<li><b>${mark} ${esc(s.label)}</b>${fields}${s.note ? ` — ${esc(s.note)}` : ''}</li>`;
  }).join('');
  return `<details class="breakdown" style="margin-top:12px">
      <summary>Extraction attempts</summary>
      <ul style="margin:10px 0 0;padding-left:20px;color:var(--ink-70);font-size:13px">${rows}</ul>
    </details>`;
}

