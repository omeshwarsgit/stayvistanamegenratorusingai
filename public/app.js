/* ------------------------------------------------------- browser capture */

/**
 * Some OTAs only serve a listing inside their own site session, so the page the
 * user is looking at is the only readable copy. This panel walks them through
 * handing that page to the tool, then waits for it to arrive.
 */
async function renderCapture(data) {
  const box = $('captureBox');
  stopCapturePolling();

  if (!data.needsCapture || !data.capture || !data.capture.supported) {
    box.hidden = true;
    box.innerHTML = '';
    return;
  }

  const snippet = await loadSnippet();
  box.hidden = false;
  box.innerHTML = `
    <div class="notice capture card">
      <h3>Capture from my browser</h3>
      <p>This OTA does not serve the listing to anything outside its own site, so retrying the URL
         will not help. Your browser can already see it — hand that page over and the analysis
         completes itself.</p>
      <ol>
        <li>Open the listing in your browser (button below).</li>
        <li>Run the capture snippet on that page — drag the blue chip to your bookmarks bar once,
            then click it on any listing; or use <em>Copy console snippet</em>, press F12 and paste
            it into the Console.</li>
        <li>Come back here. This panel is watching, and will analyse the moment it arrives.</li>
      </ol>
      <div class="row">
        <button class="btn small" id="openListingBtn">Open listing in my browser</button>
        <a class="bookmarklet" id="bookmarkletLink" href="${snippet ? snippet.bookmarklet : '#'}"
           title="Drag me to your bookmarks bar">Capture listing &rarr; drag to bookmarks</a>
        ${snippet ? `<button class="btn secondary small" data-copy="${esc(snippet.console)}">Copy console snippet</button>` : ''}
        <span class="waiting" id="captureWaiting"><span class="pulse"></span> Waiting for a capture...</span>
      </div>
      <p id="captureNote"></p>
    </div>`;

  $('bookmarkletLink').addEventListener('click', (event) => {
    // Clicking it here would run it against the dashboard, not the listing.
    event.preventDefault();
    $('captureNote').textContent = 'Drag that chip to your bookmarks bar, then click it while the listing is open.';
  });

  $('openListingBtn').addEventListener('click', async () => {
    $('captureNote').textContent = 'Opening the listing...';
    try {
      const res = await fetch('/api/open-listing', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ url: data.capture.listingUrl }),
      });
      const result = await res.json();
      $('captureNote').textContent = result.ok
        ? 'Listing opened. Run the capture snippet on that page, then come back.'
        : result.error;
    } catch {
      $('captureNote').textContent = 'Could not open a browser from here — open the listing yourself.';
    }
  });

  startCapturePolling(data.capture.listingUrl);
}

async function loadSnippet() {
  if (state.snippet) return state.snippet;
  try {
    state.snippet = await (await fetch('/api/capture/snippet')).json();
  } catch {
    state.snippet = null;
  }
  return state.snippet;
}

function startCapturePolling(listingUrl) {
  const deadline = Date.now() + 5 * 60 * 1000;
  state.capturePoll = setInterval(async () => {
    if (Date.now() > deadline) {
      stopCapturePolling();
      const waiting = $('captureWaiting');
      if (waiting) waiting.innerHTML = 'Stopped watching — click Analyze Property again after capturing.';
      return;
    }
    try {
      const status = await (await fetch(`/api/capture/status?url=${encodeURIComponent(listingUrl)}`)).json();
      if (!status.found || status.looseMatch) return;
      stopCapturePolling();
      const waiting = $('captureWaiting');
      if (waiting) waiting.innerHTML = '<span class="tick">&check;</span> Capture received — analysing...';
      runAnalysis({ fresh: false });
    } catch {
      /* server restarting; keep waiting */
    }
  }, 2000);
}

function stopCapturePolling() {
  if (state.capturePoll) {
    clearInterval(state.capturePoll);
    state.capturePoll = null;
  }
}

function setBusy(busy) {
  state.busy = busy;
  $('analyzeBtn').disabled = busy;
  $('regenerateBtn').disabled = busy;
  $('analyzeBtn').textContent = busy ? 'Analysing...' : 'Analyze Property';
  $('loading').hidden = !busy;
  if (busy) {
    $('emptyState').hidden = true;
    $('errorBox').hidden = true;
    $('results').hidden = true;
  }
}

function collectOverrides() {
  // A prefilled value is what we extracted, not a correction — only send a
  // field back if the user actually changed it.
  const text = (id) => {
    const el = $(id);
    const value = el.value.trim();
    return value && value !== (el.dataset.prefill || '') ? value : '';
  };
  const addRaw = text('fixAddUsp');
  const typed = addRaw ? addRaw.split(',').map((s) => s.trim()).filter(Boolean) : [];
  return {
    name: text('fixName'),
    location: text('fixLocation'),
    propertyType: text('fixType'),
    bedrooms: text('fixBedrooms'),
    guests: text('fixGuests'),
    bathrooms: text('fixBathrooms'),
    addUsps: [...typed, ...state.confirmed],
    removeUsps: [...state.removed],
  };
}

function clearCorrections() {
  for (const id of ['fixName', 'fixLocation', 'fixType', 'fixBedrooms', 'fixGuests', 'fixBathrooms', 'fixAddUsp']) {
    $(id).value = '';
    delete $(id).dataset.prefill;
  }
}

function resetCorrections() {
  clearCorrections();
  state.removed = new Set();
  state.confirmed = new Set();
  runAnalysis({ fresh: false });
}

/* ------------------------------------------------------------------ render */

function render(data) {
  $('errorBox').hidden = true;
  $('emptyState').hidden = true;
  $('results').hidden = false;

  renderWarnings(data);
  renderCapture(data);
  renderFacts(data);
  renderUsps(data);
  renderBest(data);
  renderOtaCards(data);
  renderSuggestions(data);
  renderCorrectionPanel(data);
  renderFoot(data);
  window.scrollTo({ top: 0, behavior: 'smooth' });
}

function renderWarnings(data) {
  const box = $('warnings');
  const items = [...(data.warnings || [])];
  if (data.ai && data.ai.error) items.push(`Claude pass: ${data.ai.error}`);
  if (!items.length) {
    box.innerHTML = '';
    return;
  }
  const partial = (data.analysis.coverage && data.analysis.coverage.partial);
  box.innerHTML = `
    <div class="notice warn section">
      <h3>${partial ? 'Partial listing information available' : 'Worth a look'}</h3>
      <ul>${items.map((w) => `<li>${esc(w)}</li>`).join('')}</ul>
    </div>`;
}

function renderFacts(data) {
  const a = data.analysis;
  const tiles = [
    ['Property Name', a.name && a.name.value, a.name],
    ['OTA', data.ota.label, { source: data.ota.supported ? 'json-ld' : 'page-text', evidence: data.ota.supported ? 'Detected from the URL' : 'Not one of the five supported OTAs' }],
    ['Property Type', a.propertyType && a.propertyType.value, a.propertyType],
    ['Location', a.location && a.location.value, a.location],
    ['Bedrooms', a.bedrooms ? `${a.bedrooms.value} BHK` : null, a.bedrooms],
    ['Guest Capacity', a.guests ? `${a.guests.value} Guests` : null, a.guests],
    ['Bathrooms', a.bathrooms ? String(a.bathrooms.value) : null, a.bathrooms],
    ['Guest Rating', a.rating ? `${a.rating.value}${a.reviewCount ? ` (${a.reviewCount.value})` : ''}` : null, a.rating],
  ];

  const usps = data.usps.titleUsps || [];
  const commodities = (data.usps.commodities || []).filter((u) => !u.titleWorthy);
  tiles.push(
    ['Top USP', usps[0] ? usps[0].label : null, usps[0] ? { source: usps[0].source, evidence: usps[0].evidence } : null],
    ['Secondary USP', usps[1] ? usps[1].label : null, usps[1] ? { source: usps[1].source, evidence: usps[1].evidence } : null],
  );

  $('facts').innerHTML = tiles.map(([label, value, meta]) => `
    <div class="fact">
      <div class="fact-label">${esc(label)}</div>
      <div class="fact-value${value ? '' : ' unknown'}">${value ? esc(value) : 'Not found'}</div>
      ${value && meta ? sourceBadge(meta) : ''}
    </div>`).join('');

  const keyAmenities = [...usps.slice(0, 6).map((u) => u.label), ...commodities.slice(0, 4).map((u) => u.label)];
  $('facts').insertAdjacentHTML('beforeend', keyAmenities.length ? `
    <div class="fact" style="grid-column:1/-1">
      <div class="fact-label">Key Amenities</div>
      <div class="fact-value" style="font-size:15px;font-family:var(--ui)">${keyAmenities.map(esc).join(' · ')}</div>
      ${data.analysis.amenityCount ? `<span class="src strong">${data.analysis.amenityCount} listed on the page</span>` : ''}
    </div>` : '');

  const parts = [];
  if (data.fetch.ok) parts.push(`Read ${Math.round((data.fetch.bytes || 0) / 1024)} KB from the property page`);
  if (data.manualUsed) parts.push('plus details you pasted');
  if (data.analysis.amenityCount) parts.push(`${data.analysis.amenityCount} amenities listed`);
  if (data.elapsedMs) parts.push(`${(data.elapsedMs / 1000).toFixed(1)}s`);
  $('extractionNote').textContent = parts.join(' · ');
}

function sourceBadge(meta) {
  const [label, tone] = SOURCE_LABEL[meta.source] || ['Source unknown', 'weak'];
  const title = meta.evidence ? `${label} — ${meta.evidence}` : label;
  return `<span class="src ${tone}" title="${esc(title)}">${esc(label)}</span>`;
}

function renderUsps(data) {
  const title = data.usps.titleUsps;
  const all = data.usps.ranked.filter((u) => u.titleWorthy);

  $('uspChecks').innerHTML = all.length
    ? all.map((u) => `
      <li class="usp-check" title="${esc(u.evidence || '')}">
        <span class="tick">&check;</span>
        <span>${esc(u.label)}${u.manual ? '<span class="tag">added by you</span>' : ''}</span>
      </li>`).join('')
    : '<li class="usp-check"><span>No standout features were found on this listing.</span></li>';

  const commodities = data.usps.commodities.filter((u) => !u.titleWorthy);
  const unconfirmed = data.usps.unconfirmed || [];
  const note = $('commodityNote');
  const parts = [];
  if (commodities.length) {
    parts.push(`Present but too common to sell a title: ${commodities.map((u) => esc(u.label)).join(', ')}.`);
  }
  if (unconfirmed.length) {
    parts.push(`Mentioned on the page but not confirmed for <em>this</em> property — nearby attractions, other
      listings and filter labels all read alike, so these are left out of every name. Click one to confirm it:
      <div class="chips">${unconfirmed.slice(0, 14).map((u) => `
        <button type="button" class="chip confirm-usp${state.confirmed.has(u.label) ? ' confirmed' : ''}"
          data-label="${esc(u.label)}" title="${esc(u.evidence || '')}">${esc(u.label)}
          <span class="x">${state.confirmed.has(u.label) ? '&check;' : '+'}</span></button>`).join('')}</div>`);
  }
  note.hidden = parts.length === 0;
  note.innerHTML = parts.join('<br><br>');

  for (const chip of note.querySelectorAll('.confirm-usp')) {
    chip.addEventListener('click', () => {
      const label = chip.dataset.label;
      if (state.confirmed.has(label)) state.confirmed.delete(label);
      else state.confirmed.add(label);
      chip.classList.toggle('confirmed');
      chip.querySelector('.x').innerHTML = state.confirmed.has(label) ? '&check;' : '+';
    });
  }

  $('uspRanked').innerHTML = title.length
    ? title.slice(0, 8).map((u, i) => `
      <li class="rank">
        <span class="rank-no">${i + 1}</span>
        <div class="rank-body">
          <div class="rank-top">
            <span class="rank-label">${esc(u.label)}</span>
            <span class="rank-strength">${u.strength}/100</span>
          </div>
          <div class="bar"><span style="width:${Math.max(4, u.strength)}%"></span></div>
          ${u.reasons && u.reasons.length ? `<div class="rank-why">${esc(u.reasons[0])}</div>` : ''}
        </div>
      </li>`).join('')
    : '<li class="rank-why">Nothing on this listing is strong enough to lead a title. Add a USP below if you know of one.</li>';
}

